namespace WinTester.Branding;

// Runtime brand profile; all user-facing name/color/logo/splash/about text must flow from here, never
// hardcoded in the UI layer. Defaults below are WinTester's own dev profile; re-skinning for a customer
// ships a different brand.json next to the executable, no rebuild required.
public sealed class BrandProfile
{
    public string AppName { get; set; } = "WinTester";
    public string CompanyName { get; set; } = "WinTester";

    // WindowBackgroundColor/AccentColor are the only two the current UI actually consumes; PrimaryColor
    // is kept for sample-schema parity and future report theming.
    public string PrimaryColor { get; set; } = "#1C1C1F";
    public string AccentColor { get; set; } = "#426BFF";
    public string WindowBackgroundColor { get; set; } = "#1C1C1F";

    public string LogoPath { get; set; } = "brand/logo.png";

    // Lives at the application root, not under /brand.
    public string SplashImagePath { get; set; } = "splash.bmp";

    public string AboutText { get; set; } = "WinTester, PC Diagnostics Suite";
    public string SupportUrl { get; set; } = "";
    public string ReportFooterText { get; set; } = "Report generated by WinTester";

    // Optional business-details block for the top of every report Empty by default.
    public BusinessDetails BusinessDetails { get; set; } = new();
}
